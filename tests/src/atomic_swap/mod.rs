/// settlement timestamps — far in the future here (year ~2286).
pub const DEFAULT_DEADLINE: u64 = 10_000_000_000;
const ATOMIC_SEND_GAS: u64 = 3_000_000;
const TX_GAS: u64 = 5_000_000;

