//! Shared engine for the end-to-end atomic-interop swap between two L1-settling ZKsync OS chains
//! (no gateway in the path), driven natively in Rust.
//!
//! One implementation, two callers:
//!   * the `atomic_swap_l1_settled` integration test (`tests/tests/atomic_swap.rs`) brings up the
//!     `ecosystem` fixture (two chains on one Anvil L1) and calls [`run_atomic_swap`];
//!   * the `atomic-swap-demo` binary (`tests/src/bin/atomic-swap-demo.rs`) reads RPCs/keys from the
//!     environment and calls the same [`run_atomic_swap`] against an already-running preset.
//!
//! The flow (bundle-model atomic swap):
//!   1. deploy + register a throwaway ERC-20 on each chain (mint to the user, approve the NTV),
//!   2. ensure the two chains are registered with each other for interop (permissionless
//!      `registerChain`; a no-op if the preset already did it at genesis),
//!   3. atomic-send both legs (burn + IMT insert), with the send-time low-nullifier index supplied
//!      by the server's Rust IMT engine (`zks_getImtLowNullifierIndex`),
//!   4. wait for each leg's commitment-tree root to settle on L1, fetch the real message proof
//!      (`zks_getL2ToL1LogProof`, messageRoot target) plus the IMT inclusion proof
//!      (`zks_getImtInclusionProof`), and wait for the L1 interop root to be imported on both chains,
//!   5. call `L2InteropHandler.executeAtomicBundle` per leg and assert both destination mints land
//!      (exact delta) and both bundles report `FullyExecuted`.
//!
//! ── Contract shapes are ARTIFACT-SOURCED ──────────────────────────────────────────────────────
//! The drift-critical protocol bindings (`InteropCenter`, `L2InteropHandler`, `AtomicFlowManager`,
//! `L2NativeTokenVault`, `IERC7786Attributes` — and every struct they reference) are generated by
//! `build.rs` from the committed `zkstack-out` ABIs of the resolved era-contracts checkout. A
//! contract-shape change fails this crate to COMPILE instead of drifting silently. The remaining
//! bindings below are stable, non-drift-prone views (a plain ERC-20, the L1/L2 bridgehub registration
//! surface, the interop-root storage view) and are declared inline.
