/// Inputs for one end-to-end atomic swap between chain A and chain B.
pub struct AtomicSwapParams {
    /// L2 RPC URL of chain A.
    pub rpc_a: String,
    /// L2 RPC URL of chain B.
    pub rpc_b: String,
    /// L1 (settlement layer) RPC URL — its chain id is folded into the flowId, and it hosts the
    /// permissionless chain-registration sender.
    pub l1_rpc: String,
    /// Depositor / recipient wallet (must be funded on both chains).
    pub signer: PrivateKeySigner,
    /// Amount chain A sends to the user on chain B.
    pub a_amount: U256,
    /// Amount chain B sends to the user on chain A.
    pub b_amount: U256,
    /// Amount minted to the depositor on each throwaway token (also the NTV approval amount).
    pub supply: U256,
    /// Flow deadline as an L1 settlement-layer timestamp (see [`DEFAULT_DEADLINE`]).
    pub deadline: u64,
    /// era-contracts checkout root, used to read the `TestnetERC20Token` creation bytecode from its
    /// forge `out/` (resolve with `protocol_ops::common::paths::contracts_root()`).
    pub era_root: PathBuf,
    /// L1 Bridgehub, used to resolve the chain-registration sender when the chains are not yet
    /// registered with each other. `None` requires the chains to be pre-registered (e.g. a preset
    /// that registers at genesis); registration is then skipped.
    pub bridgehub: Option<Address>,
    /// Atomic-interop contract layout.
    pub layout: Layout,
}

