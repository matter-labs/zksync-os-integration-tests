/// 1 ETH expressed in wei, used to fund operator accounts via L1→L2 deposits.
const ONE_ETH_WEI: alloy::primitives::U256 =
    alloy::primitives::U256::from_limbs([1_000_000_000_000_000_000u64, 0, 0, 0]);
use crate::intent::{BaseToken, ChainIntent, ChainRole, DaMode, IntentConfig, VmType};
use crate::resolved::ResolvedEcosystem;
