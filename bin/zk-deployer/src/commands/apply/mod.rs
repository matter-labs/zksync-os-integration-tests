#[derive(Parser, Debug)]
pub struct ApplyArgs {
    /// Path to intent.yaml
    #[arg(long, default_value = "intent.yaml")]
    pub intent: PathBuf,

    /// Path to state.json
    #[arg(long, default_value = "state.json")]
    pub state: PathBuf,

    /// Path to wallets.yaml (generated by `wallets generate` or `bootstrap`)
    #[arg(long, default_value = "wallets.yaml")]
    pub wallets: PathBuf,

    /// Output directory for Safe Transaction Builder bundles
    #[arg(long, default_value = "out")]
    pub out: PathBuf,

    /// Private key of the deployer (used to derive deployer address for simulation).
    /// Defaults to Anvil account #0 for local dev.
    #[arg(
        long,
        default_value = "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80"
    )]
    pub private_key: PrivateKey,

    /// Broadcast the generated Safe bundles to `--l1-rpc-url` immediately after
    /// generating them, using the deployer key and all keys found in
    /// `--wallets`. On localhost Anvil, target addresses are funded
    /// automatically via `anvil_setBalance`. Use this flag for local dev
    /// to skip the manual `dev execute-manifest` step.
    #[arg(long, default_value = "false")]
    pub broadcast: bool,

    /// Path to persist/restore Anvil L1 state between commands.
    /// Only used when `l1_rpc_url` is absent from intent.yaml (auto-Anvil mode).
    #[arg(long, default_value = "l1-state.json")]
    pub l1_state: PathBuf,

    /// Optional subdirectory for all per-run forge script IO inside the
    /// contracts checkout (`script-config/<subdir>/` etc.), so concurrent
    /// runs don't collide. Default: the conventional fixed paths.
    #[arg(long)]
    pub subdir: Option<String>,

    /// Skip the default L1→L2 deposits that fund the well-known dev wallets on
    /// each chain. Funding runs automatically on local/Anvil so a freshly
    /// deployed chain is ready to operate; pass this to opt out.
    #[arg(long, default_value = "false")]
    pub no_fund_l2: bool,
}

pub async fn run(args: ApplyArgs) -> Result<()> {
    let intent = IntentConfig::load(&args.intent)
        .with_context(|| format!("loading intent file {}", args.intent.display()))?;

    let (l1_rpc_url, _anvil) =
        crate::anvil::resolve_l1(intent.l1_rpc_url.as_deref(), &args.l1_state).await?;

    if _anvil.is_none() {
        preflight::check_l1_connectivity(&l1_rpc_url)?;
    }
    preflight::check_required_artifacts()?;

    let mut state = State::load_or_new(&args.state)?;

    let deployer_key = args.private_key.expose().to_string();
    let deployer_address = pk_to_address(&deployer_key)?;
    logger::info(format!("Deployer: {deployer_address:#x}"));

    let eco = ResolvedEcosystem::from_state(&state)?;
    let bridgehub = eco.bridgehub;
    let ctm_proxy = eco.ctm_proxy;

    let wallets = load_wallets(&args.wallets)?;

    let shared = SharedRunArgs {
        l1_rpc_url: l1_rpc_url.clone(),
        out: Some(args.out.clone()),
        subdir: args.subdir.clone(),
        forge_args: ForgeScriptArgs::default(),
    };

    let vm_type = VMOption::ZKSyncOsVM;

    // ── Chain init loop ────────────────────────────────────────────────────

    let manifest_path = args.out.join("manifest.json");

    for chain in &intent.chains {
        let prepared_key = StepKey::ChainInitPrepared(chain.chain_id);
        let applied_key = StepKey::ChainInitApplied(chain.chain_id);
        let funded_key = StepKey::ChainL2Funded(chain.chain_id);

        if !state.is_done(&prepared_key) {
            logger::step(format!("Initializing chain {}...", chain.chain_id));

            let chain_wallets = wallets
                .chains
                .get(&chain.chain_id.to_string())
                .with_context(|| format!("chain {} not found in wallets.yaml", chain.chain_id))?;

            let commit_operator = chain_wallets.operator_commit_sk.address;
            let prove_operator = chain_wallets.operator_prove_sk.address;
            let execute_operator = chain_wallets.operator_execute_sk.address;
            let owner = chain_wallets.owner.address;

            // ETH base token (intent has no `base_token`) registers as the protocol
            // sentinel address; a custom token resolves to its deployed/declared addr.
            let base_token_addr = resolve_base_token_addr(chain, &state)?.unwrap_or(ETH_BASE_TOKEN);
            let (da_type, l1_da_validator, l2_da_commitment_scheme) =
                resolve_da(chain, vm_type, &eco)?;

            let chain_id = L2ChainId::new(chain.chain_id).map_err(|e| anyhow::anyhow!("{e}"))?;

            let chain_params = NewChainParams {
                chain_id,
                base_token_addr,
                base_token_gas_price_multiplier_numerator: 1,
                base_token_gas_price_multiplier_denominator: 1,
                owner,
                commit_operator,
                prove_operator,
                execute_operator,
                token_multiplier_setter: None,
                da_mode: da_type,
                vm_type,
            };

            let input = ChainInitInput {
                ctm_proxy,
                bridgehub,
                l1_da_validator,
                chain_params,
                vm_type,
                l2_da_commitment_scheme,
                register_for_interop: false,
                create2_factory_salt: None,
                pause_deposits: false,
                evm_emulator: false,
                deploy_paymaster: false,
                make_permanent_rollup: false,
                skip_priority_txs: true,
            };

            let mut runner = ForgeRunner::new(&shared)?;

            let deployer = runner.prepare_sender(deployer_address).await?;
            let owner_wallet = runner.prepare_sender(owner).await?;

            let bridgehub_admin_addr = resolve_bridgehub_admin(&runner.rpc_url, bridgehub)
                .await
                .context("resolving bridgehub admin from L1 fork")?;
            let bridgehub_admin = runner.prepare_sender(bridgehub_admin_addr).await?;

            let manifest_start = count_manifest_bundles(&manifest_path);

            let output = chain_init(
                &mut runner,
                &deployer,
                &owner_wallet,
                &bridgehub_admin,
                &input,
            )
            .await?;

            write_output_if_requested(
                &prepared_key.to_string(),
                &shared,
                &runner,
                &input,
                &ChainInitOutputData::from_full_output(&output),
            )
            .await?;

            // Count after write_output_if_requested so the range [start, end) covers
            // the bundles just written by chain_init.
            let manifest_end = count_manifest_bundles(&manifest_path);

            logger::info(format!("  diamond proxy: {:#x}", output.diamond_proxy_addr));
            logger::info(format!("  chain admin:   {:#x}", output.chain_admin_addr));

            if preflight::is_local_rpc(&l1_rpc_url) {
                logger::step("Funding operator addresses on L1...");
                for addr in [commit_operator, prove_operator, execute_operator] {
                    crate::funding::fund(&l1_rpc_url, &deployer_key, addr)
                        .await
                        .with_context(|| format!("funding operator {addr:#x}"))?;
                    logger::info(format!("  funded {addr:#x}"));
                }
            }

            state.mark_done(
                &prepared_key,
                &ChainInitPreparedOutput {
                    diamond_proxy: output.diamond_proxy_addr,
                    chain_admin: output.chain_admin_addr,
                    manifest_start,
                    manifest_end,
                },
            )?;
            state.save(&args.state)?;
        } else {
            logger::info(format!("Skipping {prepared_key} (already done)"));
        }

        if args.broadcast && !state.is_done(&applied_key) {
            let prepared: ChainInitPreparedOutput = state
                .get_output(&prepared_key)
                .with_context(|| format!("{} not found in state", prepared_key))?;

            logger::step(format!("Applying chain bundles for {}...", chain.chain_id));
            let funder = preflight::is_local_rpc(&l1_rpc_url).then_some(deployer_key.as_str());
            apply_manifest_from(
                &manifest_path,
                prepared.manifest_start,
                Some(prepared.manifest_end),
                std::slice::from_ref(&deployer_key),
                Some(&args.wallets),
                &l1_rpc_url,
                funder,
            )
            .await
            .with_context(|| {
                format!(
                    "applying chain bundles for {} — ensure wallets.yaml contains \
                     all signing keys or supply them via --private-key",
                    chain.chain_id
                )
            })?;

            state.mark_done(&applied_key, &serde_json::json!({}))?;
            state.save(&args.state)?;
        }

        // Fund the well-known dev wallets on L2 so the chain is ready to
        // operate. Deposits are L1 priority txs (no server needed) processed in
        // the chain's first batch. Local/Anvil only, and requires the chain to
        // have been registered on L1 (applied_key done, either this run or a
        // prior one — args.broadcast alone would silently skip this on resume).
        if state.is_done(&applied_key)
            && preflight::is_local_rpc(&l1_rpc_url)
            && !args.no_fund_l2
            && !state.is_done(&funded_key)
        {
            logger::step(format!(
                "Funding default dev wallets on L2 for chain {} (priority deposits)...",
                chain.chain_id
            ));
            let base_token = resolve_base_token_addr(chain, &state)?;
            crate::l1_l2_deposit::fund_default_l2_wallets(
                &l1_rpc_url,
                bridgehub,
                chain.chain_id,
                &deployer_key,
                base_token,
            )
            .await?;

            state.mark_done(&funded_key, &serde_json::json!({}))?;
            state.save(&args.state)?;
        }
    }

    // ── Re-fund operators (idempotent) ─────────────────────────────────────

    if preflight::is_local_rpc(&l1_rpc_url) {
        logger::step("Re-funding operator addresses (idempotent)...");
        for chain in &intent.chains {
            let chain_wallets = wallets
                .chains
                .get(&chain.chain_id.to_string())
                .with_context(|| format!("chain {} not found in wallets.yaml", chain.chain_id))?;
            let commit_operator = chain_wallets.operator_commit_sk.address;
            let prove_operator = chain_wallets.operator_prove_sk.address;
            let execute_operator = chain_wallets.operator_execute_sk.address;

            for addr in [commit_operator, prove_operator, execute_operator] {
                crate::funding::fund(&l1_rpc_url, &deployer_key, addr)
                    .await
                    .with_context(|| format!("funding operator {addr:#x}"))?;
                logger::info(format!("  funded {addr:#x} (chain {})", chain.chain_id));
            }
        }
    }

    if protocol_ops::common::config::is_json_output() {
        let chain_results: serde_json::Value = intent
            .chains
            .iter()
            .filter_map(|c| {
                let key = StepKey::ChainInitPrepared(c.chain_id);
                state
                    .get_output::<ChainInitPreparedOutput>(&key)
                    .ok()
                    .map(|out| {
                        serde_json::json!({
                            "chain_id": c.chain_id,
                            "diamond_proxy": format!("{:#x}", out.diamond_proxy),
                            "chain_admin": format!("{:#x}", out.chain_admin),
                        })
                    })
            })
            .collect();
        println!(
            "{}",
            serde_json::to_string_pretty(&serde_json::json!({
                "status": "ok",
                "chains": chain_results,
            }))?
        );
    } else {
        logger::success("Apply complete.");
    }

    if let Some(ref anvil) = _anvil {
        crate::anvil::save_state(anvil, &args.l1_state).await?;
        logger::info(format!("L1 state saved to: {}", args.l1_state.display()));
    }

    Ok(())
}

/// Protocol sentinel address used for an ETH base token.
const ETH_BASE_TOKEN: Address = address!("0x0000000000000000000000000000000000000001");

/// Resolve a chain's DA registration inputs: the `DAValidatorType` passed to `register_chain`
/// (which derives the on-chain `PubdataPricingMode` from `!= Rollup`), the L1 DA validator, and
/// the L2 commitment scheme when the chain's delivery is not the blobs its kind defaults to.
///
/// This is the *delivery* axis. What the chain commits is [`resolve_pubdata_content`], and every
/// validium here commits the same logs-only region however it delivers it.
fn resolve_da(
    chain: &ChainIntent,
    vm_type: VMOption,
    eco: &ResolvedEcosystem,
) -> anyhow::Result<(DAValidatorType, Address, Option<L2DACommitmentScheme>)> {
    let blobs_validator = || -> anyhow::Result<Address> {
        if vm_type == VMOption::ZKSyncOsVM {
            eco.blobs_zksync_os_l1_da_validator.ok_or_else(|| {
                anyhow::anyhow!(
                    "ecosystem has no ZKsync OS blobs L1 DA validator — \
                     redeploy with a build that has one"
                )
            })
        } else {
            Ok(eco.rollup_l1_da_validator)
        }
    };

    Ok(match chain.da_mode {
        DaMode::Rollup => (DAValidatorType::Rollup, blobs_validator()?, None),
        // The default delivery for every kind: blobs, through the same validator a rollup uses.
        DaMode::Validium(ValidiumDa::Blobs) => {
            (DAValidatorType::LogsOnlyValidium, blobs_validator()?, None)
        }
        // Calldata goes through the standard rollup DA validator (`PUBDATA_SOURCE_CALLDATA`
        // branch). The derived scheme would be blobs, so the calldata one is named explicitly — it
        // must match the server's `pubdata_mode: Calldata` wire or every commit reverts with
        // MismatchL2DACommitmentScheme.
        DaMode::Validium(ValidiumDa::Calldata) => (
            DAValidatorType::LogsOnlyValidium,
            eco.rollup_l1_da_validator,
            Some(L2DACommitmentScheme::BlobsAndPubdataKeccak256),
        ),
        DaMode::Validium(ValidiumDa::DiscouragedNoDa) => (
            DAValidatorType::LogsOnlyValidium,
            eco.no_da_l1_validator,
            Some(L2DACommitmentScheme::EmptyNoDA),
        ),
        DaMode::Avail => (DAValidatorType::Avail, eco.avail_l1_da_validator, None),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use alloy::primitives::address;

    const ROLLUP_VALIDATOR: Address = address!("0x1111111111111111111111111111111111111111");
    const NO_DA_VALIDATOR: Address = address!("0x2222222222222222222222222222222222222222");
    const BLOBS_VALIDATOR: Address = address!("0x3333333333333333333333333333333333333333");

    fn chain(da_mode: DaMode) -> ChainIntent {
        ChainIntent {
            chain_id: 6565,
            base_token: None,
            da_mode,
        }
    }

    fn ecosystem() -> ResolvedEcosystem {
        ResolvedEcosystem {
            bridgehub: Address::ZERO,
            ctm_proxy: Address::ZERO,
            rollup_l1_da_validator: ROLLUP_VALIDATOR,
            no_da_l1_validator: NO_DA_VALIDATOR,
            avail_l1_da_validator: Address::ZERO,
            blobs_zksync_os_l1_da_validator: Some(BLOBS_VALIDATOR),
        }
    }

    /// Every validium is the same kind of chain — `LogsOnlyValidium`, which is what gives it the
    /// logs-only pubdata content — and the flavors differ only in how that pubdata is delivered.
    #[test]
    fn validium_flavors_differ_only_in_delivery() {
        let eco = ecosystem();
        for (flavor, validator, scheme) in [
            (ValidiumDa::Blobs, BLOBS_VALIDATOR, None),
            (
                ValidiumDa::Calldata,
                ROLLUP_VALIDATOR,
                Some(L2DACommitmentScheme::BlobsAndPubdataKeccak256),
            ),
            (
                ValidiumDa::DiscouragedNoDa,
                NO_DA_VALIDATOR,
                Some(L2DACommitmentScheme::EmptyNoDA),
            ),
        ] {
            let resolved =
                resolve_da(&chain(DaMode::Validium(flavor)), VMOption::ZKSyncOsVM, &eco).unwrap();
            assert_eq!(
                resolved,
                (DAValidatorType::LogsOnlyValidium, validator, scheme),
                "{flavor:?}"
            );
        }
    }

    #[test]
    fn a_rollup_delivers_through_blobs() {
        assert_eq!(
            resolve_da(&chain(DaMode::Rollup), VMOption::ZKSyncOsVM, &ecosystem()).unwrap(),
            (DAValidatorType::Rollup, BLOBS_VALIDATOR, None)
        );
    }
}
